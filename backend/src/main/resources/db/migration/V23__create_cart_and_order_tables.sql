CREATE TABLE public.cart_item (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES public.usuario (id) ON DELETE CASCADE,
    producto_id INTEGER NOT NULL REFERENCES public.producto (id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    creado_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_cart_item_user_product UNIQUE (usuario_id, producto_id)
);

CREATE INDEX idx_cart_item_user ON public.cart_item (usuario_id);

CREATE TABLE public.customer_order (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES public.usuario (id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (
        status IN (
            'PENDIENTE',
            'ENVIADO',
            'ENTREGADO',
            'CANCELADO'
        )
    ),
    total NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'PEN',
    creado_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_customer_order_user_created ON public.customer_order (usuario_id, creado_at DESC);

CREATE TABLE public.order_item (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES public.customer_order (id) ON DELETE CASCADE,
    producto_id INTEGER NOT NULL REFERENCES public.producto (id) ON DELETE RESTRICT,
    product_name VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'PEN'
);

CREATE INDEX idx_order_item_order ON public.order_item (order_id);
